-- Drop the table if it already exists to start clean
DROP TABLE IF EXISTS jobs CASCADE;

-- Create the table with all constraints built-in
CREATE TABLE jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status text NOT NULL DEFAULT 'PENDING' 
        CONSTRAINT jobs_status_check CHECK (status = ANY (ARRAY['PENDING'::text, 'RUNNING'::text, 'SUCCEEDED'::text, 'DEAD'::text])),
    job_type text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    priority integer NOT NULL DEFAULT 0 
        CONSTRAINT check_priority_non_negative CHECK (priority >= 0),
    run_at timestamp with time zone NOT NULL DEFAULT now(),
    attempts integer NOT NULL DEFAULT 0 
        CONSTRAINT check_attempts_non_negative CHECK (attempts >= 0),
    max_attempts integer NOT NULL DEFAULT 5 
        CONSTRAINT check_max_attempts_non_negative CHECK (max_attempts >= 0),
    lease_owner text,
    lease_expires_at timestamp with time zone,
    last_error text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    -- Table-level constraint ensuring both lease columns are either set or null
    CONSTRAINT check_lease_pair_validity CHECK (
        (lease_owner IS NULL AND lease_expires_at IS NULL) 
        OR 
        (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)
    )
);
